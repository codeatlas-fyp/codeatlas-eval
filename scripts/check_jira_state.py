"""Check the frozen-case evidence contract for Jira state on the real cache: can status, priority, assignee and
resolution be rebuilt at each pool PR's cutoff from timestamped records alone?

    python scripts/check_jira_state.py                 # all repos, writes eval/results/jira_state_check.md
    python scripts/check_jira_state.py --repo spark

For every included pool row and each of its keys, the issue is read exactly as freeze_case.py reads it
(common.jira_issue_for: the REST cache in eval/pool/raw/ first, else the mail archive), and state_at() rebuilds
the four fields at the row's merge time. The report counts, per repo and field, how many were reconstructed,
unverifiable (incomplete changelog, change with no old value) or unavailable (no history in the source), and
lists the reasons. Nothing is fetched when a cached copy exists; nothing is ever filled from the issue as fetched.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from pathlib import Path

from common import EVAL, read_csv, repo_cfg
from jira_archive import STATE_FIELDS, issue_source, state_at

OUT = EVAL / "results" / "jira_state_check.md"


def check(repo: str, offline: bool) -> tuple[Counter, Counter, Counter, int]:
    from common import cached_rest_issue, jira_issue_for
    cfg = repo_cfg(repo)
    counts: Counter = Counter()
    reasons: Counter = Counter()
    sources: Counter = Counter()
    n = 0
    for row in read_csv(EVAL / "pool" / f"{repo}_pool.csv"):
        if row.get("included") != "yes":
            continue
        for key in filter(None, row.get("keys_found", "").split(";")):
            try:
                issue = (cached_rest_issue(repo, key, row["pr_number"]) if offline
                         else jira_issue_for(cfg, key, row["pr_number"]))
            except Exception as e:  # noqa: BLE001
                issue = None
                reasons[f"not readable: {type(e).__name__}"] += 1
            if issue is None:
                sources["none (not cached)" if offline else "none"] += 1
                for f in STATE_FIELDS:
                    counts[(f, "unavailable")] += 1
                n += 1
                continue
            sources[issue_source(issue)] += 1
            st = state_at(issue, row["merged_at"])
            if st["changelog_complete"] is None and issue_source(issue) != "apache_mail_archive":
                reasons["changelog length not recorded (completeness unknown; field still rebuilt)"] += 1
            for f, v in st["fields"].items():
                counts[(f, v["reconstruction"])] += 1
                if v["reconstruction"] != "reconstructed":
                    reasons[v["note"].split(";")[0][:90]] += 1
            n += 1
    return counts, reasons, sources, n


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", nargs="+", default=["airflow", "arrow", "spark"])
    ap.add_argument("--online", action="store_true", help="also read the mail archive for keys not in the cache")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    lines = ["# Jira state at the cutoff: can it be rebuilt from timestamped records?", "",
             "Generated by `scripts/check_jira_state.py`" + (" (cache and archive)." if a.online else
                                                          " (cache only; keys not cached count as unavailable)."),
             "One row per (pool PR, key). Status category is never rebuilt (it comes from today's workflow "
             "configuration).", ""]
    for repo in a.repo:
        counts, reasons, sources, n = check(repo, offline=not a.online)
        lines += [f"## {repo}: {n} PR-key pairs", "",
                  "Sources: " + ", ".join(f"{s} {c}" for s, c in sources.most_common()), "",
                  "| Field | reconstructed | unverifiable | unavailable |", "|---|---|---|---|"]
        for f in STATE_FIELDS:
            lines.append(f"| {f} | {counts[(f, 'reconstructed')]} | {counts[(f, 'unverifiable')]} | "
                         f"{counts[(f, 'unavailable')]} |")
        if reasons:
            lines += ["", "Reasons a field was not rebuilt:", ""] + [f"- {r}: {c}" for r, c in reasons.most_common(8)]
        lines.append("")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"written: {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
